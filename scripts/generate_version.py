#!/usr/bin/env python3
"""Synchronize stable package versions from library.json using Python 3.10+.

Commands: sync, check, bump patch|minor|major, set SEMVER. Exit 0 means success;
check returns 1 for stale generated fields, and invalid arguments, metadata,
templates or I/O return 2. Sync/bump/set write only changed UTF-8/LF files after
validating all inputs. I/O failure can leave a partial sync; rerun after repair.
No Git, timestamps, firmware identity, subprocesses or network are consulted.
The root is the directory above this script, including in extracted source trees.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys


_SEMVER = re.compile(
    r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)"
    r"(?:-([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?"
    r"(?:\+([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?"
)
_MAX_COMPONENT = 4294967295


def _parse_semver(version: str) -> tuple[int, int, int]:
    """Validate ASCII SemVer and uint32 core fields; return its numeric core."""
    if not isinstance(version, str) or (match := _SEMVER.fullmatch(version)) is None:
        raise ValueError(f"Invalid semantic version: {version!r}")
    core = tuple(int(match[index]) for index in (1, 2, 3))
    if any(value > _MAX_COMPONENT for value in core):
        raise ValueError("Version core components must fit uint32_t")
    if match[4] is not None:
        for identifier in match[4].split("."):
            if identifier.isdigit() and len(identifier) > 1 and identifier.startswith("0"):
                raise ValueError("Numeric prerelease identifiers must not have leading zeros")
    return core


def _render_header(version: str) -> bytes:
    """Render only stable constexpr package values with complete generated Doxygen."""
    major, minor, patch = _parse_semver(version)
    return f'''/// @file Version.h
/// @brief Stable package version; no Git, clock, firmware identity or device work.
/// @note Generated by scripts/generate_version.py from library.json. Do not edit manually.
#pragma once

#include <cstdint>

namespace TUSB32x {{

/// @brief Major SemVer component, in the uint32 range; no I2C or allocation.
inline constexpr std::uint32_t VERSION_MAJOR = {major};
/// @brief Minor SemVer component, in the uint32 range; no I2C or allocation.
inline constexpr std::uint32_t VERSION_MINOR = {minor};
/// @brief Patch SemVer component, in the uint32 range; no I2C or allocation.
inline constexpr std::uint32_t VERSION_PATCH = {patch};
/// @brief Full package SemVer, including suffixes; static lifetime, not flashed firmware identity.
inline constexpr char VERSION[] = "{version}";

}}  // namespace TUSB32x
'''.encode("utf-8")


def _replace_single(
    text: str, declaration: str, pattern: str, value: str, field: str
) -> str:
    """Require one declaration, then replace its canonical maintained value.

    Count declarations independently of quoting/comments so an alternate-form
    override cannot hide behind the stricter replacement template.
    """
    count = len(re.findall(declaration, text, flags=re.MULTILINE))
    if count != 1:
        raise ValueError(f"Expected exactly one {field} declaration; found {count}")
    updated, count = re.subn(
        pattern, lambda match: match[1] + value + match[2], text, flags=re.MULTILINE
    )
    if count != 1:
        raise ValueError(f"Expected exactly one {field} field; found {count}")
    return updated


def _outputs(root: Path, version: str) -> dict[Path, bytes]:
    """Preflight all managed templates and render their complete desired bytes."""
    core = ".".join(str(value) for value in _parse_semver(version))
    cmake = (root / "CMakeLists.txt").read_text(encoding="utf-8")
    cmake = _replace_single(
        cmake, r'^[ \t]*(?i:set)\s*\(\s*(?:TUSB32X_VERSION|"TUSB32X_VERSION")(?=[\s)])',
        r'^(set\(TUSB32X_VERSION ")[^"\r\n]*("\)[ \t]*)$',
        version, "CMake full version"
    )
    cmake = _replace_single(
        cmake, r'^[ \t]*(?i:project)\s*\(\s*(?:TUSB32x|"TUSB32x")(?=[\s)])',
        r'^(project\(TUSB32x VERSION )[^\s)]+( LANGUAGES CXX\)[ \t]*)$',
        core, "CMake project version"
    )
    component = _replace_single(
        (root / "idf_component.yml").read_text(encoding="utf-8"),
        r'''^(?:version|"version"|'version')[ \t]*:''',
        r'^(version:[ \t]*")[^"\r\n]*("[ \t]*)$', version, "component version"
    )
    doxygen = _replace_single(
        (root / "Doxyfile").read_text(encoding="utf-8"),
        r'^[ \t]*PROJECT_NUMBER[ \t]*\+?=',
        r'^(PROJECT_NUMBER[ \t]*=[ \t]*")[^"\r\n]*("[ \t]*)$', version, "Doxygen version"
    )
    return {
        root / "include/TUSB32x/Version.h": _render_header(version),
        root / "CMakeLists.txt": cmake.encode("utf-8"),
        root / "idf_component.yml": component.encode("utf-8"),
        root / "Doxyfile": doxygen.encode("utf-8"),
    }


def main(argv: list[str] | None = None) -> int:
    """Run CLI arguments against this script's root; return 0/1/2 as documented.

    None reads process arguments. Only sync/bump/set mutate files, with no writes
    for equal bytes. All paths are local; no temporary fixture or Git is created.
    argparse reports invalid command syntax with exit 2 before metadata access.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("sync", help="repair generated version fields")
    commands.add_parser("check", help="check without writing; stale fields exit 1")
    bump = commands.add_parser("bump", help="increment core; drop suffixes and reset lower fields")
    bump.add_argument("part", choices=("patch", "minor", "major"))
    set_version = commands.add_parser("set", help="set a complete SemVer")
    set_version.add_argument("version")
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parents[1]
    try:
        manifest_path = root / "library.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        if not isinstance(manifest, dict) or "version" not in manifest:
            raise ValueError("library.json must contain a version string")
        current = manifest["version"]
        core = list(_parse_semver(current))
        version = current
        if args.command == "set":
            version = args.version
        elif args.command == "bump":
            index = {"major": 0, "minor": 1, "patch": 2}[args.part]
            core[index] += 1
            for lower in range(index + 1, 3):
                core[lower] = 0
            version = ".".join(str(value) for value in core)
        _parse_semver(version)
        outputs = _outputs(root, version)
        if version != current:
            manifest["version"] = version
            outputs[manifest_path] = (
                json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
            ).encode("utf-8")
        stale = [path for path, expected in outputs.items()
                 if not path.is_file() or path.read_bytes() != expected]
        if args.command == "check":
            for path in stale:
                print(f"Stale: {path.relative_to(root).as_posix()}")
            return 1 if stale else 0
        for path in stale:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(outputs[path])
            print(f"Updated: {path.relative_to(root).as_posix()}")
        return 0
    except (OSError, UnicodeError, ValueError) as error:
        print(f"Version error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
